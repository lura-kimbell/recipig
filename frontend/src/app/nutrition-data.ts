/**
 * Reference nutrition for common ingredients, per 100 g, based on USDA
 * FoodData Central (SR Legacy / Foundation Foods, public domain). Values are
 * typical figures for the food as bought (raw meat, dry pasta, canned beans
 * drained), rounded; they are for an estimate, not a label.
 *
 * Columns: names, calories (kcal), protein, fat, carbs, fiber, sugar (g),
 * sodium (mg), then grams per US cup, grams per item, and grams per named unit.
 * The first matching name decides nothing on its own: the longest name that
 * matches an ingredient line wins, so "brown sugar" beats "sugar".
 *
 * Keep this file free of imports (see nutrition.ts) so the tests run under plain Node.
 */

interface Row {
  names: string[];
  per100g: { calories: number; protein: number; fat: number; carbs: number; fiber: number; sugar: number; sodium: number };
  gramsPerCup?: number;
  gramsEach?: number;
  units?: Record<string, number>;
}

function f(
  names: string,
  calories: number,
  protein: number,
  fat: number,
  carbs: number,
  fiber: number,
  sugar: number,
  sodium: number,
  gramsPerCup?: number,
  gramsEach?: number,
  units?: Record<string, number>,
): Row {
  return {
    names: names.split('|'),
    per100g: { calories, protein, fat, carbs, fiber, sugar, sodium },
    ...(gramsPerCup ? { gramsPerCup } : {}),
    ...(gramsEach ? { gramsEach } : {}),
    ...(units ? { units } : {}),
  };
}

