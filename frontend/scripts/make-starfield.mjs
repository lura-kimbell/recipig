// Generates public/backgrounds/starfield.svg, the Aurora theme's night sky.
//
// One big image with stars at random positions, so the sky never visibly repeats the way
// a tiled CSS pattern does. A fixed seed keeps the result the same on every run; change
// SEED for a different sky. Run: node scripts/make-starfield.mjs
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const SEED = 20261028;
const WIDTH = 1600;
const HEIGHT = 1000;

/** mulberry32: a small seeded random number generator. */
function random(seed) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const rand = random(SEED);
const between = (lo, hi) => lo + rand() * (hi - lo);
const pick = (items) => items[Math.floor(rand() * items.length)];
/** Roughly bell-shaped, for scattering stars around the Milky Way's centre line. */
const gaussian = () => (rand() + rand() + rand() + rand() - 2) / 2;

// Mostly white, some blue-white, a few warm, like real stars.
const TINTS = ['#ffffff', '#ffffff', '#ffffff', '#dbe6ff', '#c9d8ff', '#fff4e0', '#ffe9c7'];

// The Milky Way band runs from the top right to the bottom left, through the middle,
// matching the faint band drawn in styles.css.
const BAND = { x: WIDTH / 2, y: HEIGHT / 2, dx: -0.47, dy: 0.88, width: 150 };

function bandPoint() {
  const along = between(-900, 900);
  const across = gaussian() * BAND.width;
  return [BAND.x + BAND.dx * along - BAND.dy * across, BAND.y + BAND.dy * along + BAND.dx * across];
}

const r = (n) => Math.round(n * 100) / 100;
const stars = [];
const star = (x, y, radius, opacity, fill) => {
  if (x < 0 || y < 0 || x > WIDTH || y > HEIGHT) return;
  stars.push(`<circle cx="${r(x)}" cy="${r(y)}" r="${r(radius)}" fill="${fill}" opacity="${r(opacity)}"/>`);
};

// Faint background stars, evenly scattered.
for (let i = 0; i < 800; i++) star(between(0, WIDTH), between(0, HEIGHT), between(0.6, 1.1), between(0.3, 0.8), pick(TINTS));
// Extra faint stars crowding the Milky Way.
for (let i = 0; i < 650; i++) star(...bandPoint(), between(0.5, 0.95), between(0.25, 0.65), pick(TINTS));
// Medium stars.
for (let i = 0; i < 130; i++) star(between(0, WIDTH), between(0, HEIGHT), between(1.1, 1.7), between(0.7, 1), pick(TINTS));
// A few bright stars with a soft glow.
const glows = [];
for (let i = 0; i < 14; i++) {
  const x = between(20, WIDTH - 20);
  const y = between(20, HEIGHT - 20);
  const size = between(3.5, 6.5);
  glows.push(`<circle cx="${r(x)}" cy="${r(y)}" r="${r(size)}" fill="url(#glow${i % 2})"/>`);
  star(x, y, between(1.1, 1.6), 1, pick(['#ffffff', '#fff6e0', '#e6eeff']));
}

const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${WIDTH} ${HEIGHT}" preserveAspectRatio="xMidYMid slice">
<!-- Generated by scripts/make-starfield.mjs (seed ${SEED}); edit the script, not this file. -->
<defs>
<radialGradient id="glow0"><stop offset="0" stop-color="#ffffff" stop-opacity="0.9"/><stop offset="0.3" stop-color="#cfdcff" stop-opacity="0.35"/><stop offset="1" stop-color="#cfdcff" stop-opacity="0"/></radialGradient>
<radialGradient id="glow1"><stop offset="0" stop-color="#fff6e0" stop-opacity="0.9"/><stop offset="0.3" stop-color="#ffe2b8" stop-opacity="0.3"/><stop offset="1" stop-color="#ffe2b8" stop-opacity="0"/></radialGradient>
</defs>
${glows.join('\n')}
${stars.join('\n')}
</svg>
`;

const out = join(dirname(fileURLToPath(import.meta.url)), '..', 'public', 'backgrounds', 'starfield.svg');
mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, svg);
console.log(`Wrote ${stars.length} stars (${Math.round(svg.length / 1024)} KB) to ${out}`);
